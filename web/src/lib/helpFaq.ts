export const OFFLINE_NOTE = '小织暂时离线，先看看这些常见问题';

/** 离线兜底：把匹配到的条目（或几条常见问题）拼成 Markdown */
export function offlineAnswer(question: string): string {
  const hit = answer(question);
  const items = hit ? [hit] : HELP.filter((h) => QUICK.slice(0, 3).includes(h.id));
  const body = items.map((it) => `**${it.q}**\n\n${it.a.map((l) => (/^(\d+\.|•)/.test(l) ? l.replace(/^•\s*/, '- ') : l)).join('\n\n')}`);
  return `_${OFFLINE_NOTE}_\n\n${body.join('\n\n---\n\n')}`;
}

