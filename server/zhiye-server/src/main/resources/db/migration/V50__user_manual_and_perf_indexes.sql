### 五、企业生态对接指南（左侧「生态」页）
平台提供四大受控企业能力，**所有密钥均经 AES-256-GCM 加密托管在服务端，绝不进入前端源码或浏览器**：
1. **飞书群机器人（告警与卡片推送）**：
   - 在飞书群设置中添加「自定义机器人」，复制 Webhook 地址（如启用签名校验可一并填入密钥）保存到织页「生态 → 飞书连接器」。
   - 点卡片上的 **「测试连通」** 即可收到测试交互卡片，后续直接对 AI 说「异常时用我的飞书机器人发告警卡片」。
2. **飞书多维表格（同步读写业务台账）**：
   - 选择「飞书多维表格」，**直接粘贴浏览器地址栏里的完整多维表格链接**，系统会自动提取 `appToken` 与 `tableId`，再填入飞书自建应用的 `App ID` 与 `App Secret` 保存即可。
   - 请确保该飞书应用已被添加为目标多维表格的「可编辑」协作者。
3. **企业 AGW 数据源（安全读取公司内部接口）**：
   - 在「生态 → 数据源」或输入框 **「＋ → 数据源」** 中点击 **「选择可调用 API」**，即可从当前华星账号已获授权的 AGW 接口目录一键导入并试调用。
   - 绑定到应用后，前端通过 `window.zhiye.source.query(...)`、全栈后端通过平台代理网关取数，单应用最多绑定 **100 个** 数据源。
4. **团队知识库 & 远端 HTTP MCP**：
   - **团队知识库**：直接粘贴部门业务规范、指标口径、字段字典（单条最多 6 万字），编码智能体开发时自动按关键词检索对齐口径。
   - **远端 HTTP MCP**：填写标准 Streamable HTTP / JSON-RPC 2.0 地址，点击 **「自动拉取工具」** 即可自动探测暴露的 MCP 工具清单。
5. **多租户隐私隔离承诺**：你在「生态」页自助添加的飞书连接器、私有知识库与 HTTP MCP **仅归属你的个人工作空间**，其他员工无法在列表中看到，也无法测试或通过应用代理调用你的任何私有凭据与知识库内容。

