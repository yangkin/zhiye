### 六、全栈托管、云服务与数据持久化
1. **什么时候用「共享云服务」？**
   - 表单收集、多人台账、轻审批、需要文件上传或调用大模型分析时，在工作台点击 **「共享云服务」** 即可自动建表与配置权限，**无冷启动、零运维**。
2. **什么时候用「全栈应用 / 服务托管」？**
   - 需要自定义后端接口（Java Spring Boot / Node / Python / Go）或导入外部工程时使用。可在「服务托管」面板配置：
     - **资源配额**：单容器最高 **1C 1G**，默认 **2 天（2880 分钟）** 无访问自动休眠释放算力，再次访问自动透明唤醒（1～10 秒）。
     - **持久化存储**：文件与 SQLite 统一写入 `DATA_DIR`（`/data`），结构化数据可一键开启 **托管 PostgreSQL 独立 Schema**（按应用独立数据库角色隔离，并支持只读数据预览）。
     - **端口免冲突**：代码监听环境变量 `PORT`（`0.0.0.0`）即可，平台自动分配可用端口并检测占用，无需担心端口撞车。

