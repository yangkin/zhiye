### 三、上传附件与 Excel / CSV 直接做看板
1. **如何用真实表格一键生成看板**：在创造页或工作台输入框，直接**拖入或点「＋」上传**你的 `.xlsx` / `.csv` 文件，并写明需求（例如：「按这份良率明细表做一个按产线、机台、日期多维度筛选的交互看板，带异常 Top10 和导出功能」）。织页会读取真实表头与样例数据生成匹配字段的可视化看板，并且页面通常自带本地 Excel/CSV 再导入能力。
2. **支持格式与限制**：单条消息最多 **5 个** 附件，单文件 **≤ 10 MB**；支持 **图片**（PNG/JPG/WebP，可照截图还原页面）、**PDF**、新版 Office（`.docx` / `.xlsx` / `.pptx`）及文本/代码文件（暂不支持旧版 `.doc` / `.xls` / `.ppt`）。
3. **附件在会话中的生命周期**：
   - **同一会话内全程有效**：上传过的文件与图片会保留在该会话上下文中，后续多轮追问（如「把刚才表里第三列改成百分比」）仍可直接引用，无需重复上传。
   - **跨会话严格隔离**：新建空白会话后不会带入上一段会话的附件，保障数据边界清晰。

