package com.tcl.csot.zhiye.service.runtime;

import com.tcl.csot.zhiye.config.ServiceRuntimeProperties;

/**
 * 为 Python / Node.js / Java / Go 单体及前后端一体项目自动生成生产级非 root 分层缓存 Dockerfile。
 * 核心优化：
 * 1. 先 COPY 依赖清单（package*.json / requirements.txt / pom.xml / go.mod）并安装依赖，再 COPY 业务源码，最大化复用 Docker / Kaniko 构建层缓存；
 * 2. 支持通过构建参数注入企业内网镜像源（NPM_REGISTRY / PIP_INDEX_URL / MAVEN_MIRROR_URL / GOPROXY）；
 * 3. 运行态严格以非 root UID 10001 启动，兼容 K8s 受限 PodSecurity。
 */
public final class DockerfileGenerator {
    private DockerfileGenerator() {}

    public static String generate(ServiceRuntimeDetector.Spec spec, ServiceRuntimeProperties props) {
        String runtime = spec.runtime() == null ? "node" : spec.runtime().toLowerCase();
        String backDir = cleanDir(spec.backendDir());
        String frontDir = cleanDir(spec.frontendDir());
        int port = spec.port() > 0 ? spec.port() : 8080;

        StringBuilder sb = new StringBuilder();
        sb.append("# Auto-generated by Zhiye Deploy Engine V2 (").append(spec.framework()).append(" · Layered Cache)\n");

        if (!frontDir.isEmpty()) {
            sb.append("FROM ").append(props.baseImageNode()).append(" AS frontend-builder\n");
            sb.append("ARG NPM_REGISTRY=").append(props.npmRegistry()).append("\n");
            sb.append("ARG NPM_TARBALL_CDN=").append(props.npmTarballCdn()).append("\n");
            sb.append("WORKDIR /frontend\n");
            // 优先仅拷贝依赖清单以命中 Docker/Kaniko 依赖缓存层
            sb.append("COPY ").append(frontDir).append("/package*.json ./\n");
            sb.append("RUN if [ -f package.json ]; then \\\n");
            sb.append("      if [ -n \"$NPM_REGISTRY\" ]; then npm config set registry \"$NPM_REGISTRY\"; fi && \\\n");
            appendNpmTarballRewrite(sb);
            sb.append("      (npm ci --no-audit --no-fund || npm install --no-audit --no-fund); \\\n");
            sb.append("    fi\n");
            sb.append("COPY ").append(frontDir).append("/ ./\n");
            sb.append("RUN if [ -f package.json ]; then npm run build; \\\n");
            sb.append("    else mkdir -p dist && cp -r . dist/ 2>/dev/null || true; fi\n\n");
        }

        switch (runtime) {
            case "python" -> appendPython(sb, spec, props, backDir, frontDir, port);
            case "java" -> appendJava(sb, spec, props, backDir, frontDir, port);
            case "go" -> appendGo(sb, spec, props, backDir, frontDir, port);
            default -> appendNode(sb, spec, props, backDir, frontDir, port);
        }
        return sb.toString();
    }

    private static void appendNpmTarballRewrite(StringBuilder sb) {
        sb.append("      if [ -n \"$NPM_TARBALL_CDN\" ]; then \\\n");
        sb.append("        if [ ! -f package-lock.json ]; then npm install --package-lock-only --ignore-scripts --no-audit --no-fund; fi && \\\n");
        sb.append("        node -e 'const fs=require(\"fs\"),p=\"package-lock.json\",j=JSON.parse(fs.readFileSync(p,\"utf8\")),hosts=new Set([\"registry.npmjs.org\",\"registry.npmmirror.com\"]),cdn=process.env.NPM_TARBALL_CDN.replace(/[/]+$/,\"\");const walk=o=>{if(!o||typeof o!==\"object\")return;if(typeof o.resolved===\"string\"){try{const u=new URL(o.resolved);if(hosts.has(u.hostname)){const a=u.pathname.split(\"/\"),i=a.lastIndexOf(\"-\");if(i>1&&i===a.length-2){const n=a.slice(1,i).join(\"/\"),f=a[i+1],b=n.split(\"/\").pop(),v=f.startsWith(b+\"-\")&&f.endsWith(\".tgz\")?f.slice(b.length+1,-4):\"\";if(n&&v)o.resolved=cdn+\"/\"+n+\"/\"+v+\"/\"+f}}}catch{}};Object.values(o).forEach(walk)};walk(j);fs.writeFileSync(p,JSON.stringify(j,null,2)+\"\\n\")'; fi && \\\n");
    }

    private static void appendPython(StringBuilder sb, ServiceRuntimeDetector.Spec spec, ServiceRuntimeProperties props,
                                     String backDir, String frontDir, int port) {
        String srcPrefix = backDir.isEmpty() ? "" : backDir + "/";
        sb.append("FROM ").append(props.baseImagePython()).append("\n");
        sb.append("ARG PIP_INDEX_URL=").append(props.pipIndexUrl()).append("\n");
        sb.append("ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PORT=").append(port).append(" DATA_DIR=/data\n");
        sb.append("WORKDIR /app\n");
        // 分层缓存：先安装依赖清单（requirements.txt / pyproject.toml），业务代码变更不触发重装
        sb.append("COPY ").append(srcPrefix).append("requirements*.txt ").append(srcPrefix).append("pyproject.toml* ./\n");
        sb.append("RUN if [ -f requirements.txt ]; then \\\n");
        sb.append("      if [ -n \"$PIP_INDEX_URL\" ]; then pip install --no-cache-dir -i \"$PIP_INDEX_URL\" -r requirements.txt; \\\n");
        sb.append("      else pip install --no-cache-dir -r requirements.txt; fi; \\\n");
        sb.append("    fi\n");
        sb.append("COPY ").append(backDir.isEmpty() ? "." : backDir + "/").append(" ./\n");
        sb.append("RUN if [ ! -f requirements.txt ] && [ -f pyproject.toml ]; then \\\n");
        sb.append("      if [ -n \"$PIP_INDEX_URL\" ]; then pip install --no-cache-dir -i \"$PIP_INDEX_URL\" .; \\\n");
        sb.append("      else pip install --no-cache-dir .; fi; \\\n");
        sb.append("    fi\n");
        if (!frontDir.isEmpty()) {
            sb.append("COPY --from=frontend-builder /frontend/dist ./static\n");
        }
        sb.append("RUN addgroup --gid 10001 appgroup 2>/dev/null || true && \\\n");
        sb.append("    adduser --uid 10001 --gid 10001 --disabled-password --gecos \"\" appuser 2>/dev/null || true && \\\n");
        sb.append("    mkdir -p /data && chown -R 10001:10001 /app /data\n");
        sb.append("USER 10001\n");
        sb.append("EXPOSE ").append(port).append("\n");
        String start = spec.startCmd() == null || spec.startCmd().isBlank() ? "python3 main.py" : spec.startCmd();
        sb.append("CMD [\"sh\", \"-c\", ").append(jsonStr(start)).append("]\n");
    }

    private static void appendNode(StringBuilder sb, ServiceRuntimeDetector.Spec spec, ServiceRuntimeProperties props,
                                   String backDir, String frontDir, int port) {
        String srcPrefix = backDir.isEmpty() ? "" : backDir + "/";
        sb.append("FROM ").append(props.baseImageNode()).append("\n");
        sb.append("ARG NPM_REGISTRY=").append(props.npmRegistry()).append("\n");
        sb.append("ARG NPM_TARBALL_CDN=").append(props.npmTarballCdn()).append("\n");
        sb.append("ENV NODE_ENV=production PORT=").append(port).append(" DATA_DIR=/data\n");
        sb.append("WORKDIR /app\n");
        // 分层缓存：先拷贝 package*.json 安装 node_modules，再拷贝业务代码
        sb.append("COPY ").append(srcPrefix).append("package*.json ./\n");
        sb.append("RUN if [ -f package.json ]; then \\\n");
        sb.append("      if [ -n \"$NPM_REGISTRY\" ]; then npm config set registry \"$NPM_REGISTRY\"; fi && \\\n");
        appendNpmTarballRewrite(sb);
        sb.append("      (npm ci --include=dev --no-audit --no-fund || npm install --include=dev --no-audit --no-fund); \\\n");
        sb.append("    fi\n");
        sb.append("COPY ").append(backDir.isEmpty() ? "." : backDir + "/").append(" ./\n");
        if (!frontDir.isEmpty()) {
            sb.append("COPY --from=frontend-builder /frontend/dist ./public\n");
        }
        if (spec.buildCmd() != null && !spec.buildCmd().isBlank()) {
            sb.append("RUN ").append(spec.buildCmd()).append("\n");
        }
        sb.append("RUN mkdir -p /data && chown -R 10001:10001 /app /data 2>/dev/null || true\n");
        sb.append("USER 10001\n");
        sb.append("EXPOSE ").append(port).append("\n");
        String start = spec.startCmd() == null || spec.startCmd().isBlank() ? "npm start" : spec.startCmd();
        sb.append("CMD [\"sh\", \"-c\", ").append(jsonStr(start)).append("]\n");
    }

    private static void appendJava(StringBuilder sb, ServiceRuntimeDetector.Spec spec, ServiceRuntimeProperties props,
                                   String backDir, String frontDir, int port) {
        String srcPrefix = backDir.isEmpty() ? "" : backDir + "/";
        sb.append("FROM ").append(props.baseImageJavaBuild()).append(" AS builder\n");
        sb.append("ARG MAVEN_MIRROR_URL=").append(props.mavenMirrorUrl()).append("\n");
        sb.append("RUN if [ -n \"$MAVEN_MIRROR_URL\" ]; then \\\n");
        sb.append("      mkdir -p /root/.m2 && printf '%s' '<settings><mirrors><mirror><id>mirror</id><mirrorOf>central</mirrorOf><url>'\"$MAVEN_MIRROR_URL\"'</url></mirror></mirrors></settings>' > /root/.m2/settings.xml; \\\n");
        sb.append("    fi\n");
        sb.append("WORKDIR /src\n");
        // 分层缓存：先拷贝 pom.xml / build.gradle 预拉取依赖，再拷贝全部源码编译
        sb.append("COPY ").append(srcPrefix).append("pom.xml* ").append(srcPrefix).append("build.gradle* ").append(srcPrefix).append("settings.gradle* ./\n");
        sb.append("RUN if [ -f pom.xml ]; then mvn -B dependency:go-offline || true; fi\n");
        sb.append("COPY ").append(backDir.isEmpty() ? "." : backDir + "/").append(" ./\n");
        if (!frontDir.isEmpty()) {
            sb.append("COPY --from=frontend-builder /frontend/dist ./src/main/resources/static\n");
        }
        sb.append("RUN if [ -f pom.xml ]; then \\\n");
        sb.append("      mvn -B -DskipTests -Dcheckstyle.skip=true -Dspotless.check.skip=true package && \\\n");
        sb.append("      cp $(ls target/*.jar | grep -v original | head -n 1) /src/app.jar; \\\n");
        sb.append("    elif [ -f build.gradle ] || [ -f build.gradle.kts ]; then \\\n");
        sb.append("      (test -x ./gradlew && ./gradlew build -x test || gradle build -x test) && \\\n");
        sb.append("      cp $(ls build/libs/*.jar | grep -v plain | head -n 1) /src/app.jar; \\\n");
        sb.append("    else \\\n");
        sb.append("      mkdir -p /src/out && javac -d /src/out $(find . -name '*.java'); \\\n");
        sb.append("    fi\n\n");

        sb.append("FROM ").append(props.baseImageJavaRuntime()).append("\n");
        sb.append("ENV PORT=").append(port).append(" DATA_DIR=/data\n");
        sb.append("WORKDIR /app\n");
        sb.append("COPY --from=builder /src/app.jar ./app.jar\n");
        sb.append("RUN mkdir -p /data && chown -R 10001:10001 /app /data 2>/dev/null || true\n");
        sb.append("USER 10001\n");
        sb.append("EXPOSE ").append(port).append("\n");
        String start = spec.startCmd() == null || spec.startCmd().isBlank()
                ? "java -jar app.jar --server.port=${PORT:-8080}" : spec.startCmd();
        sb.append("CMD [\"sh\", \"-c\", ").append(jsonStr(start)).append("]\n");
    }

    private static void appendGo(StringBuilder sb, ServiceRuntimeDetector.Spec spec, ServiceRuntimeProperties props,
                                 String backDir, String frontDir, int port) {
        String srcPrefix = backDir.isEmpty() ? "" : backDir + "/";
        sb.append("FROM ").append(props.baseImageGoBuild()).append(" AS builder\n");
        sb.append("ARG GOPROXY=").append(props.goProxy()).append("\n");
        sb.append("WORKDIR /src\n");
        // 分层缓存：先拷贝 go.mod / go.sum 下载模块依赖，再拷贝源码编译
        sb.append("COPY ").append(srcPrefix).append("go.mod* ").append(srcPrefix).append("go.sum* ./\n");
        sb.append("RUN if [ -n \"$GOPROXY\" ]; then export GOPROXY=\"$GOPROXY\"; fi && \\\n");
        sb.append("    if [ -f go.mod ]; then go mod download; fi\n");
        sb.append("COPY ").append(backDir.isEmpty() ? "." : backDir + "/").append(" ./\n");
        sb.append("RUN if [ -n \"$GOPROXY\" ]; then export GOPROXY=\"$GOPROXY\"; fi && \\\n");
        sb.append("    CGO_ENABLED=0 GOOS=linux ").append(spec.buildCmd() == null || spec.buildCmd().isBlank() ? "go build -o app ." : spec.buildCmd()).append("\n\n");

        sb.append("FROM ").append(props.baseImageGoRuntime()).append("\n");
        sb.append("ENV PORT=").append(port).append(" DATA_DIR=/data\n");
        sb.append("WORKDIR /app\n");
        sb.append("COPY --from=builder /src/app ./app\n");
        if (!frontDir.isEmpty()) {
            sb.append("COPY --from=frontend-builder /frontend/dist ./static\n");
        }
        sb.append("RUN mkdir -p /data && chown -R 10001:10001 /app /data 2>/dev/null || true\n");
        sb.append("USER 10001\n");
        sb.append("EXPOSE ").append(port).append("\n");
        sb.append("CMD [\"./app\"]\n");
    }

    private static String cleanDir(String dir) {
        if (dir == null) return "";
        return dir.trim().replace('\\', '/').replaceAll("^/+|/+$", "");
    }

    private static String jsonStr(String s) {
        return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }
}
