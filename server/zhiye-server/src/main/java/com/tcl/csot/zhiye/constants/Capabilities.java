package com.tcl.csot.zhiye.constants;

/**
 * 织页一次能做多大、哪些做不到。计划、会话、生成、修改、小织的提示词都引用这里，调上限只改这一处。
 * 默认不弹窗中断：单次任务连续执行上限由 zhiye.task.max-agent-turns（默认 200 步）与 max-duration-minutes（默认 45 分钟）兜底。
 */
public final class Capabilities {
    private Capabilities() {}

    /** 云数据库表的上限（与 CloudService 的表结构校验一致）；页面、角色和流程状态数量不限 */
    public static final int MAX_TABLES = 50;

    /** 规模上限 */
    public static final String LIMITS = """
            规模要求：
            - 页面数量不限，按业务需要设计
            - 云数据库表不超过 %d 张；角色数量和每条业务流程的状态数量不限，按业务需要设计
            - 单次任务连续执行上限为 200 步 / 45 分钟（过程中不打断用户确认）：内容多时按优先级把核心流程先完整做通，再做其余部分，不要因为内容多就偷工减料或留半成品
            """.formatted(MAX_TABLES);

    /** 平台做不到的事和替代做法 */
    public static final String UNSUPPORTED = """
            | 做不到的需求 | 替代做法 |
            | --- | --- |
            | 原生 App、小程序、桌面客户端、扫码从外网访问 | 做成网页应用，连着公司内网的电脑或手机浏览器打开 |
            | 直连生产数据库，或往 MES / ERP / SAP 等系统写数据 | 接口在 AGW 侧登记后，通过「数据源 → 选择可调用 API」添加并只读使用；没有接口时先用 Excel / CSV 导入 |
            | 微服务集群（Spring Cloud/Nacos/Dubbo）、消息队列（Kafka/RabbitMQ）、独立 Redis/ES、长时间常驻后台守护进程 | 单体前后端全栈（Vue 3 + Java Spring Boot、React + Node.js Express、Python FastAPI/Flask、Go）可直接在对话中通过「全栈应用」生成或「导入代码并部署」托管（单应用上限 1C 1G，默认 2 天无访问自动休眠，内置托管 PostgreSQL 与 `/data` 持久化卷）；轻量场景可用「页面 + 共享云服务（云数据库 + 云文件存储 + Deno 云函数）」；微服务/MQ/GPU 集群请用独立云主机或 K8s |
            | 支付、短信、邮件群发，开放给公司外部用户 | 不做；内部流程用状态提醒、待办列表代替 |
            | 实时多人协同编辑、音视频通话、直播、3D、语音识别 | 不做；协作改成「提交 → 审批」，各自录入 |
            | 训练模型、自建 AI 服务 | 用平台的应用内 AI（对话、抽取、总结、识图） |
            | 统一登录以外的账号体系 | 用平台的「员工登录」（公司统一登录） |
            """;

    /** 创造计划：超过上限就拆期，只把第一期写成本次范围 */
    public static final String PLAN = """

            # 能力范围（写计划前先对照）
            """ + LIMITS + """
            需求超过上面的规模时**不要硬塞进一次**：只把最核心、能独立用起来的部分写成「第一期」，计划里的内容与功能、验收标准都只写第一期；
            在「本期不实现」之后加一节「## 分期计划」，用表格（期次 / 内容 / 说明）列出第一期和后续各期，每期都要能在上面的规模内做完，第一期标「本期」；
            JSON 里 "scale" 写 "phased"，没有超过就写 "normal" 且不要写「分期计划」一节。
            需求里有平台做不到的部分时，在计划末尾加一节「## 做不到的部分」（表格：需求 / 原因 / 替代做法），计划正文按替代做法写，不要假装能做；没有就不要写这一节。
            """ + UNSUPPORTED;

    /** 创造页会话：开工前先把做不到的、太大的说清楚 */
    public static final String CHAT = """

            # 能力范围（判断能不能做、一次做多大）
            """ + LIMITS + """
            - 需求明显超过这个规模（超过 50 张数据表、整套 ERP / MES、多部门多角色的复杂流程）：如实说「一次做不完」，建议先做第一期，
              列出第一期包含什么（在上面的规模内）、后面几期各做什么，问用户是否按这个第一期开始；用户同意后再输出 [[build:类型]]。
            - 需求里有平台做不到的部分：直接说做不到，并给出下表的替代做法，不要含糊答应。
            """ + UNSUPPORTED;

    /** 生成：只实现第一期 */
    public static final String GENERATE = """
            - 计划里如果有「分期计划」，**只实现第一期（本期）**；后续各期不要实现，也不要放「敬请期待」之类的假入口
            """;

    /** 修改：一次改不完时先做最重要的部分 */
    public static final String MODIFY = """
            - 这次要求的改动量如果明显超过一次能做完的范围（例如整体推翻重做、一次新增多个独立业务模块），先完成最核心、能独立用起来的一部分并保证可用，
              在「需要注意」里写明还剩哪些没做，[[next]] 里给出接着做的下一句
            """;

    /** 小织（使用帮助） */
    public static final String HELP = """
            ## 能力范围
            """ + LIMITS + """
            - 需求太大时，织页会先做第一期（创造计划里会有「分期计划」），做完后在工作台说「继续做第二期」接着加。
            - 单次任务默认可连续执行最多 200 步 / 45 分钟，过程中不会弹框打断用户；如需提前中止可随时点输入框右下角「停止」。若超大型任务触及单次上限，已写好的部分会自动保留，点「重试」即可无缝接着做。
            - 平台做不到的事：
            """ + UNSUPPORTED;
}
